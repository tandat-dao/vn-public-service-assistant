def build_document_draft_prompt(
    document_type: str,
    personal_data: dict,
) -> str:
    """Build the LLM system prompt for drafting the body section only.

    The LLM writes ONLY the body section. The structural wrapper
    (quốc hiệu, tiêu ngữ, personal data block, closing formula) is
    assembled by assemble_document(), not by the LLM.

    Args:
        document_type:  One of the DOCUMENT_TYPE_CONFIGS keys.
        personal_data:  Dict of personal data fields (may be empty).

    Returns:
        System prompt string to pass to LLMService.async_invoke().

    Raises:
        ValueError: If document_type is not in DOCUMENT_TYPE_CONFIGS.
    """
    if document_type not in DOCUMENT_TYPE_CONFIGS:
        raise ValueError(f"Unsupported document type: {document_type}")

    cfg = DOCUMENT_TYPE_CONFIGS[document_type]
    ten_van_ban = cfg["ten_van_ban"]
    body_instruction = cfg["body_instruction"]
    max_words = cfg["max_words"]

    return f"""Bạn là trợ lý soạn thảo văn bản hành chính Việt Nam.

## Nhiệm vụ
Soạn phần NỘI DUNG THÂN VĂN BẢN cho: **{ten_van_ban}**

## Hướng dẫn soạn thảo
{body_instruction}

## Giới hạn tối đa: {max_words} từ.

## Quy tắc bắt buộc
1. Chỉ viết phần nội dung thân văn bản.
   KHÔNG viết quốc hiệu, tiêu ngữ, thông tin cá nhân, hoặc phần ký tên
   — những phần đó đã được xử lý tự động bởi hệ thống.
2. KHÔNG bịa đặt thông tin cá nhân, số liệu, hoặc căn cứ pháp lý
   không có trong dữ liệu được cung cấp.
3. Sử dụng văn phong hành chính trang trọng, chuẩn mực.
4. Nếu thiếu thông tin cụ thể, dùng placeholder trong dấu ngoặc vuông
   ví dụ: [địa chỉ nơi đề nghị đăng ký], [lý do cụ thể].
5. Trả lời HOÀN TOÀN bằng tiếng Việt."""


def assemble_document(
    document_type: str,
    personal_data: dict,
    body_text: str,
    filing_jurisdiction: str | None = None,
) -> str:
    """Assemble a complete Vietnamese administrative document.

    Combines the standard structural wrapper (quốc hiệu, tiêu ngữ),
    personal data block, LLM-generated body, and closing formula
    per Nghị định 30/2020/NĐ-CP.

    Args:
        document_type:       One of the DOCUMENT_TYPE_CONFIGS keys.
        personal_data:       Dict of personal data fields (may be empty).
        body_text:           LLM-generated body section text.
        filing_jurisdiction: Optional scope code (e.g. "VN-HCM-26968").

    Returns:
        Complete document string ready for display or copy-paste.

    Raises:
        ValueError: If document_type is not in DOCUMENT_TYPE_CONFIGS.
    """
    if document_type not in DOCUMENT_TYPE_CONFIGS:
        raise ValueError(f"Unsupported document type: {document_type}")

    cfg = DOCUMENT_TYPE_CONFIGS[document_type]
    ten_van_ban = cfg["ten_van_ban"]
    kinh_gui = cfg["kinh_gui"]
    dia_danh = _resolve_dia_danh(filing_jurisdiction)

    ho_ten = personal_data.get("full_name") or "[Họ và tên]"
    ngay_sinh = _format_date(personal_data.get("date_of_birth"))
    so_cccd = personal_data.get("id_number") or "[Số CCCD/CMND]"
    dia_chi = personal_data.get("raw_address") or "[Địa chỉ thường trú]"
    ho_ten_ky = ho_ten  # same as ho_ten for the signature line

    return (
        "CỘNG HÒA XÃ HỘI CHỦ NGHĨA VIỆT NAM\n"
        "Độc lập – Tự do – Hạnh phúc\n"
        "────────────────────────────\n"
        "\n"
        f"{ten_van_ban}\n"
        "\n"
        f"Kính gửi: {kinh_gui}\n"
        "\n"
        f"Tôi là: {ho_ten}\n"
        f"Ngày sinh: {ngay_sinh}\n"
        f"Số CCCD/CMND: {so_cccd}\n"
        f"Địa chỉ thường trú: {dia_chi}\n"
        "\n"
        f"{body_text}\n"
        "\n"
        "Tôi xin cam kết những thông tin trên là đúng sự thật\n"
        "và chịu trách nhiệm trước pháp luật về nội dung đã khai.\n"
        "\n"
        "Kính đề nghị Quý cơ quan xem xét và giải quyết.\n"
        "\n"
        "Trân trọng kính trình.\n"
        "\n"
        f"        {dia_danh}, ngày ... tháng ... năm ...\n"
        "                  Người làm đơn\n"
        "             (Ký và ghi rõ họ tên)\n"
        "\n"
        f"                  {ho_ten_ky}"
    )
