_FILING_JURISDICTION_MAP: dict[str, str] = {
    "VN-HCM": "TP. Hồ Chí Minh",
    "VN-HAN": "TP. Hà Nội",
    "VN-DN":  "TP. Đà Nẵng",
    "VN-CT":  "TP. Cần Thơ",
    "VN-HP":  "TP. Hải Phòng",
}


def _resolve_dia_danh(filing_jurisdiction: str | None) -> str:
    """Map a filing_jurisdiction code to a Vietnamese city/province name."""
    if not filing_jurisdiction or filing_jurisdiction == "VN":
        return ".........."
    # Check exact match first (e.g. "VN-HCM")
    if filing_jurisdiction in _FILING_JURISDICTION_MAP:
        return _FILING_JURISDICTION_MAP[filing_jurisdiction]
    # Check prefix match (e.g. "VN-HCM-26968" → "TP. Hồ Chí Minh")
    for prefix, name in _FILING_JURISDICTION_MAP.items():
        if filing_jurisdiction.startswith(prefix):
            return name
    return ".........."


def _format_date(value: object) -> str:
    """Format a date or date-string as DD/MM/YYYY for document output."""
    if value is None:
        return "[Ngày sinh]"
    if isinstance(value, date):
        return value.strftime("%d/%m/%Y")
    # Handle ISO strings like "1990-01-15"
    s = str(value)
    if len(s) == 10 and s[4] == "-" and s[7] == "-":
        try:
            parts = s.split("-")
            return f"{parts[2]}/{parts[1]}/{parts[0]}"
        except (IndexError, ValueError):
            pass
    return s or "[Ngày sinh]"


